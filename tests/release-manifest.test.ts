import {afterEach,expect,it} from "vitest";
import {mkdtempSync,mkdirSync,writeFileSync,rmSync,readFileSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {createHash} from "node:crypto";
import {writeReleaseManifest} from "../scripts/release-manifest.ts";
const dirs:string[]=[]; const sha="a".repeat(40);
afterEach(()=>{for(const dir of dirs.splice(0))rmSync(dir,{recursive:true,force:true});});
function fixture(code:string){const root=mkdtempSync(join(tmpdir(),"ordertruth-release-"));dirs.push(root);mkdirSync(join(root,"assets"));mkdirSync(join(root,"lab"));mkdirSync(join(root,"owner"));writeFileSync(join(root,"index.html"),'<script type="module" src="/assets/judge-test.js"></script>');writeFileSync(join(root,"assets/judge-test.js"),code);writeFileSync(join(root,"lab/index.html"),"Historical Lab");writeFileSync(join(root,"owner/index.html"),"Owner");return root;}
it("describes actual generated bytes and requires all public entry points",()=>{
 const code=`const source="${sha}";`; const root=fixture(code);
 const manifest=writeReleaseManifest(root,sha,"production",new Date("2026-11-07T00:00:00Z"));
 expect(manifest.sourceSha).toBe(sha);expect(manifest.backendContract).toBe("phase1-core-v1");expect(manifest.builtAt).toBe("2026-11-07T00:00:00.000Z");
 expect(manifest.assets.find(a=>a.path==="/assets/judge-test.js")).toEqual({path:"/assets/judge-test.js",bytes:Buffer.byteLength(code),sha256:createHash("sha256").update(code).digest("hex")});
 expect(JSON.parse(readFileSync(join(root,"release.json"),"utf8"))).toEqual(manifest);
 rmSync(join(root,"lab/index.html"));expect(()=>writeReleaseManifest(root,sha,"production")).toThrow();
});
it("reads the template literals emitted by the production minifier",()=>{
 expect(writeReleaseManifest(fixture('const source=`'+sha+'`;'),sha,"production").sourceSha).toBe(sha);
});
it("refuses missing, stale and contradictory compiled identities",()=>{
 for(const code of ["no identity",`const source="${"b".repeat(40)}";`,`const source="${sha}"; const stale="${"b".repeat(40)}";`]){
  expect(()=>writeReleaseManifest(fixture(code),sha,"production")).toThrow();
 }
 expect(()=>writeReleaseManifest(fixture(`const source="${sha}";`),"invalid","production")).toThrow();
});
