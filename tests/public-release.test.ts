import {expect,it} from "vitest";
import {createHash} from "node:crypto";
import {verifyPublicRelease} from "../scripts/public-release.ts";
it("downloads generated bytes and refuses a tampered asset or wrong manifest source",async()=>{
 const sha="a".repeat(40),code=`const source="${sha}";`;
 const files:Record<string,string>={'/assets/judge-test.js':code,'/index.html':'<script src="/assets/judge-test.js"></script>','/lab/index.html':'Historical Lab','/owner/index.html':'Owner'};
 const manifest={sourceSha:sha,builtAt:"2026-11-07T00:00:00Z",target:"production",backendContract:"phase1-core-v1",judgeEntry:"/assets/judge-test.js",assets:Object.entries(files).map(([path,bytes])=>({path,bytes:Buffer.byteLength(bytes),sha256:createHash("sha256").update(bytes).digest("hex")}))};
 const read=(bytes:string)=>async(url:string|URL|Request)=>new Response(String(url).includes('/release.json')?JSON.stringify(manifest):new URL(String(url)).pathname===manifest.judgeEntry?bytes:files[new URL(String(url)).pathname],{status:200});
 expect((await verifyPublicRelease('https://example.com',sha,read(code))).assetsVerified).toBe(4);
 await expect(verifyPublicRelease('https://example.com',sha,read('tampered'))).rejects.toThrow();
 await expect(verifyPublicRelease('https://example.com',"b".repeat(40),read(code))).rejects.toThrow();
 const original=manifest.assets;manifest.assets=original.slice(0,1);
 await expect(verifyPublicRelease('https://example.com',sha,read(code))).rejects.toThrow();
 manifest.assets=original;manifest.assets.push({path:'/api/auth/get-session',bytes:0,sha256:'a'.repeat(64)});
 await expect(verifyPublicRelease('https://example.com',sha,read(code))).rejects.toThrow();
 manifest.assets.pop();
 manifest.assets[0]!.path='//elsewhere.example/script.js';
 await expect(verifyPublicRelease('https://example.com',sha,read(code))).rejects.toThrow();
});
