import {expect,it} from "vitest";
import {createHash} from "node:crypto";
import {verifyPublicRelease} from "../scripts/public-release.ts";
it("downloads generated bytes and refuses a tampered asset or wrong manifest source",async()=>{
 const sha="a".repeat(40),code=`const source="${sha}";`;
 const manifest={sourceSha:sha,builtAt:"2026-11-07T00:00:00Z",target:"production",backendContract:"phase1-core-v1",judgeEntry:"/assets/judge-test.js",assets:[{path:"/assets/judge-test.js",bytes:Buffer.byteLength(code),sha256:createHash("sha256").update(code).digest("hex")}]};
 const read=(bytes:string)=>async(url:string|URL|Request)=>new Response(String(url).includes('/release.json')?JSON.stringify(manifest):bytes,{status:200});
 expect((await verifyPublicRelease('https://example.com',sha,read(code))).assetsVerified).toBe(1);
 await expect(verifyPublicRelease('https://example.com',sha,read('tampered'))).rejects.toThrow();
 await expect(verifyPublicRelease('https://example.com',"b".repeat(40),read(code))).rejects.toThrow();
 manifest.assets[0]!.path='//elsewhere.example/script.js';
 await expect(verifyPublicRelease('https://example.com',sha,read(code))).rejects.toThrow();
});
