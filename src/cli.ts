import { randomUUID } from "node:crypto";
import { ConfigError, loadConfigFromDotEnv } from "./config.ts";
import { CheckoutError } from "./checkout-service.ts";
import { PayPalError } from "./paypal/client.ts";
import { createRuntime } from "./runtime.ts";
import { resolve } from "node:path";
import { checkWebhookRegistration } from "./webhooks/registration.ts";
import { webhookStatus } from "./webhooks/status.ts";

/**
 * Gate 0 operator CLI. Prints only non-sensitive metadata. Usage:
 *   pnpm cli oauth-check
 *   pnpm cli create [--redirect]     # --redirect: Sandbox approval-URL fallback
 *   pnpm cli status <orderId>        # local DB only
 *   pnpm cli readback <orderId>      # GET from PayPal, no writes to PayPal
 *   pnpm cli capture <orderId>       # requires buyer approval (order status APPROVED)
 *   pnpm cli db-check                # list persisted attempts (restart proof)
 *   pnpm cli reconcile               # readback-only settlement of unsettled attempts (GET only)
 *   pnpm cli webhook-status          # local DB only, opened read-only; counts, no PII or credentials
 *   pnpm cli webhook-check <https tunnel origin>  # GET the configured webhook registration (read-only)
 */
const [cmd, arg, ...rest] = process.argv.slice(2);
const corr = `cli_${randomUUID()}`;
const out = (o: unknown) => console.log(JSON.stringify(o, null, 2));

try {
  if (cmd === "webhook-status") {
    // Read-only path: no runtime (which would open the store read-write and migrate it).
    const cfg = loadConfigFromDotEnv();
    out({ step: "WEBHOOK STATUS (local DB, read-only)", ...webhookStatus(resolve(cfg.databasePath), { ceiling: cfg.webhookIngress.maxStoredUnverified }) });
  } else {
    const rt = createRuntime();
    try {
      switch (cmd) {
        case "oauth-check":
          out({ step: "AUTH", correlationId: corr, ...(await rt.paypal.checkAuth({ correlationId: corr })) });
          break;
        case "create": {
          const redirect = arg === "--redirect" || rest.includes("--redirect");
          const base = `http://localhost:${rt.config.port}`;
          // Each CLI create is a new checkout (fresh checkout key generated by the service).
          const r = await rt.checkout.createOrder(corr, { redirect: redirect ? { returnUrl: `${base}/return`, cancelUrl: `${base}/cancel` } : undefined });
          out({ step: "CREATE", correlationId: corr, ...r, evidenceFiles: rt.checkout.evidenceFiles });
          break;
        }
        case "status":
          out(rt.checkout.status(arg ?? ""));
          break;
        case "readback":
          out({ step: "READBACK", correlationId: corr, ...(await rt.checkout.readback(arg ?? "", corr)) });
          break;
        case "capture":
          out({ step: "CAPTURE+READBACK", correlationId: corr, ...(await rt.checkout.capture(arg ?? "", corr)) });
          break;
        case "reconcile":
          out({ step: "RECONCILE (GET only)", correlationId: corr, ...(await rt.checkout.reconcile(corr)) });
          break;
        case "db-check":
          out({
            pid: process.pid,
            databasePath: rt.config.databasePath,
            attempts: rt.store.listAttempts().map((a) => ({ id: a.id, orderId: a.paypal_order_id, state: a.state, captureId: a.capture_id, captureStatus: a.capture_status, captured_minor: a.captured_minor, updated_at: a.updated_at, evidenceCount: rt.store.listEvidence(a.id).length })),
          });
          break;
        case "webhook-check": {
          const id = rt.config.paypal.webhookId;
          if (!id) throw new ConfigError("PAYPAL_WEBHOOK_ID is not set", ["PAYPAL_WEBHOOK_ID"]);
          const r = await checkWebhookRegistration(rt.paypal, id, arg ?? "", corr);
          out({ step: "WEBHOOK REGISTRATION CHECK (GET only)", correlationId: corr, ...r });
          if (!r.ok) process.exitCode = 5;
          break;
        }
        default:
          console.error("usage: pnpm cli <oauth-check|create [--redirect]|status <id>|readback <id>|capture <id>|reconcile|db-check|webhook-status|webhook-check <url>>");
          process.exitCode = 64;
      }
    } finally {
      rt.store.close();
    }
  }
} catch (err) {
  if (err instanceof ConfigError) {
    console.error(`Configuration error (keys: ${err.keys.join(", ")})`);
    process.exitCode = 2;
  } else if (err instanceof PayPalError) {
    out({ error: "paypal", kind: err.kind, httpStatus: err.httpStatus, debugId: err.debugId, issues: err.issues, outcomeUnknown: err.outcomeUnknown, correlationId: corr });
    process.exitCode = 3;
  } else if (err instanceof CheckoutError) {
    out({ error: err.code, message: err.message, correlationId: corr });
    process.exitCode = 4;
  } else {
    console.error((err as Error).name, (err as Error).message);
    process.exitCode = 1;
  }
}
