import { mkdtempSync,mkdirSync,writeFileSync,readFileSync } from 'node:fs';
import { join,resolve } from 'node:path';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { verifySnapshot } from './snapshot-checkpoint.mjs';
const root=mkdtempSync(join(resolve('.work/runs/ai-analysis-completion/temp'),'snapshot-test-'));
const base=join(root,'docs/evidence/investigator-eval-stage2/pre-unblinding-snapshot');mkdirSync(join(base,'files'),{recursive:true});
const sha=b=>createHash('sha256').update(b).digest('hex');
writeFileSync(join(root,'input'),'ORIGINAL');writeFileSync(join(base,'files/input'),'ORIGINAL');
const manifest={protocol:'A4_USER_APPROVED_UNCOMMITTED_SNAPSHOT',files:[{source:'input',copy:'files/input',bytes:8,sha256:sha('ORIGINAL'),verifySourceBeforeUnblinding:true}]};
const save=()=>{const bytes=JSON.stringify(manifest);writeFileSync(join(base,'manifest.json'),bytes);return sha(bytes);};
let hash=save();assert.equal(verifySnapshot(root,hash).manifest.files.length,1);
assert.throws(()=>verifySnapshot(root,'0'.repeat(64)),/checkpoint hash/);
writeFileSync(join(root,'input'),'CHANGED');assert.throws(()=>verifySnapshot(root,hash),/Working source/);writeFileSync(join(root,'input'),'ORIGINAL');
writeFileSync(join(base,'files/input'),'CHANGED');assert.throws(()=>verifySnapshot(root,hash),/Snapshot copy/);writeFileSync(join(base,'files/input'),'ORIGINAL');
manifest.files[0].copy='../../../../escape';hash=save();assert.throws(()=>verifySnapshot(root,hash),/escapes/);
manifest.files[0].copy='files/input';manifest.files[0].source='../../escape';hash=save();assert.throws(()=>verifySnapshot(root,hash),/escapes/);
manifest.files[0].source='input';manifest.protocol='WRONG';hash=save();assert.throws(()=>verifySnapshot(root,hash),/Wrong checkpoint/);
assert.equal(readFileSync(join(root,'input'),'utf8'),'ORIGINAL');
console.log(JSON.stringify({checks:8,passed:8,failed:0,scope:'Synthetic snapshot integrity/tamper/path tests only; no live sealed data accessed'}));
